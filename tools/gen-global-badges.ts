// Regenerates src/twitchbadges.ts — the built-in snapshot of Twitch's global
// chat badges (set/version → CDN image uuid + title) that renders global badge
// art when no Twitch app credentials are configured.
//
// Accepts either input shape:
//   - Chatterino's resources/twitch-badges.json (MIT): a backup of the Helix
//     list, `{ "<set_id>": [{ id, title, image: ".../badges/v1/<uuid>/" }] }`
//   - a raw Helix `GET /helix/chat/badges/global` response:
//     `{ data: [{ set_id, versions: [{ id, title, image_url_1x, … }] }] }`
//
// Usage:
//   deno run --allow-read --allow-write=src/twitchbadges.ts \
//     tools/gen-global-badges.ts <input.json> [src/twitchbadges.ts]
//
// Every uuid is validated; an entry whose image URL isn't a Twitch badge CDN
// URL fails the run rather than shipping a broken image.

const UUID = /^[0-9a-f-]{36}$/;
const CDN = /^https:\/\/static-cdn\.jtvnw\.net\/badges\/v1\/([^/]+)\/?\d?$/;

type Entry = { set: string; version: string; uuid: string; title: string };

function obj(x: unknown): Record<string, unknown> | null {
  return typeof x === "object" && x !== null && !Array.isArray(x)
    ? x as Record<string, unknown>
    : null;
}

function entry(
  set: unknown,
  version: unknown,
  title: unknown,
  image: unknown,
): Entry {
  const where = `${String(set)}/${String(version)}`;
  if (typeof set !== "string" || !set || set.includes("/")) {
    throw new Error(`bad set id: ${where}`);
  }
  if (typeof version !== "string" || !version || version.includes("/")) {
    throw new Error(`bad version id: ${where}`);
  }
  const uuid = typeof image === "string" ? CDN.exec(image)?.[1] : undefined;
  if (!uuid || !UUID.test(uuid)) {
    throw new Error(`${where}: not a badge CDN image: ${String(image)}`);
  }
  return {
    set,
    version,
    uuid,
    title: typeof title === "string" ? title.trim() : "",
  };
}

function parse(json: unknown): Entry[] {
  const root = obj(json);
  if (!root) throw new Error("input is not a JSON object");
  const out: Entry[] = [];
  if (Array.isArray(root.data)) {
    // Helix: data[].versions[].
    for (const s of root.data) {
      const set = obj(s);
      if (!set || !Array.isArray(set.versions)) {
        throw new Error(`malformed set: ${JSON.stringify(s)}`);
      }
      for (const v of set.versions) {
        const ver = obj(v);
        out.push(entry(set.set_id, ver?.id, ver?.title, ver?.image_url_1x));
      }
    }
    return out;
  }
  // Chatterino backup: { set_id: [{ id, title, image }] }.
  for (const [set, versions] of Object.entries(root)) {
    if (!Array.isArray(versions)) throw new Error(`malformed set: ${set}`);
    for (const v of versions) {
      const ver = obj(v);
      out.push(entry(set, ver?.id, ver?.title, ver?.image));
    }
  }
  return out;
}

// Set id, then version numerically when both are numbers (bits/1 < bits/100).
function compare(a: Entry, b: Entry): number {
  if (a.set !== b.set) return a.set < b.set ? -1 : 1;
  const na = Number(a.version);
  const nb = Number(b.version);
  if (/^\d+$/.test(a.version) && /^\d+$/.test(b.version)) return na - nb;
  return a.version < b.version ? -1 : a.version > b.version ? 1 : 0;
}

function render(entries: Entry[]): string {
  const lines = entries.map((e) =>
    `  ${JSON.stringify(`${e.set}/${e.version}`)}: [${
      JSON.stringify(e.uuid)
    }, ${JSON.stringify(e.title)}],`
  );
  return `// GENERATED by tools/gen-global-badges.ts — do not edit by hand.
//
// Twitch's global chat badges (moderator, VIP, broadcaster, Prime, bits, …) as
// "set/version" → [image uuid, title]. The image lives at
// https://static-cdn.jtvnw.net/badges/v1/<uuid>/1|2|3 (18/36/72px; see
// cdnBadgeArt in badges.ts). Built in so global badges render as images with
// zero configuration.
//
// Provenance: Chatterino's resources/twitch-badges.json (MIT licensed), a
// backup copy of Helix GET /helix/chat/badges/global. Live Helix data, fetched
// when Twitch app credentials are configured, always wins over this snapshot;
// it is only the fallback for badges Helix hasn't supplied.
//
// Regenerate from that backup or from a raw Helix /chat/badges/global
// response:
//   deno run --allow-read --allow-write=src/twitchbadges.ts \\
//     tools/gen-global-badges.ts <input.json> [src/twitchbadges.ts]

/** ${entries.length} global badge versions, keyed "set/version". */
// deno-fmt-ignore
export const GLOBAL_BADGES: Readonly<Record<string, readonly [uuid: string, title: string]>> = {
${lines.join("\n")}
};
`;
}

if (import.meta.main) {
  const [input, output = "src/twitchbadges.ts"] = Deno.args;
  if (!input) {
    console.error(
      "usage: tools/gen-global-badges.ts <input.json> [src/twitchbadges.ts]",
    );
    Deno.exit(2);
  }
  const entries = parse(JSON.parse(await Deno.readTextFile(input)));
  const seen = new Set<string>();
  for (const e of entries) {
    const key = `${e.set}/${e.version}`;
    if (seen.has(key)) throw new Error(`duplicate badge: ${key}`);
    seen.add(key);
  }
  entries.sort(compare);
  await Deno.writeTextFile(output, render(entries));
  console.log(`wrote ${entries.length} badge versions to ${output}`);
}
